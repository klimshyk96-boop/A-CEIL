/* Перевірка розбору голосових розмірів: node tests/voice-number.test.cjs */
const assert=require("assert");
const V=require("../js/core/aceil-voice-number.js");
const cases=[
 ["три двадцять п'ять",325],["триста двадцять п'ять",325],["три метри двадцять п'ять сантиметрів",325],
 ["3,25",325],["3 25",325],["325",325],["три п'ять",350],["три нуль п'ять",305],
 ["три тисячі двісті п'ятдесят",3250],["3250",3250],["3250 мм",325],
 ["1300",1300],["тисяча триста",1300],["тринадцять метрів",1300],["13,5",1350],["тринадцять п'ятдесят",1350],["тисяча двісті",1200],["1050",1050],["тринадцять тридцять",1330],
 ["три",3],["чотири",4],["шість",6],["дев'ять",9],["12",12],["сто двадцять шість",126],["двісті сімдесят вісім",278],
 ["дві п'ятдесят",250],["двісті п'ятдесят",250],["дванадцять п'ятдесят",1250],["три метри п'ять",305],["п'ятсот",500],
 ["три два п'ять",325],["три метри",300],["3 м 25",325],["3м25",325],["три двісті п'ятдесят",325],
 ["три двадцать пять",325],["четыре пятьдесят",450],["сто п'ятдесят",150],["сорок п'ять",45],["три десять",310],["чотири метри п'ятдесят",450],
 ["чотири",400,{smallMeters:true}],["три",300,{smallMeters:true}]
];
for(const [t,e,o] of cases){const r=V.parse(t,o);assert.ok(r,"не розібрано: "+t);assert.strictEqual(r.cm,e,t+" → "+r.cm+", очікувалось "+e);}
for(const t of ["привіт","давай на пиво","","тринадцять двадцять п'ять шість сім"]){assert.strictEqual(V.parse(t),null,"мало бути не розібрано: "+t);}
const cmds={"назад":"back","стоп":"stop","скасувати":"clear","далі":"next","отмена":"clear","Стоп!":"stop"};
for(const k in cmds)assert.strictEqual(V.command(k),cmds[k],k);
assert.strictEqual(V.command("три двадцять п'ять далі"),null,"команда не береться, коли є число");
console.log("voice-number: "+cases.length+" розборів і "+Object.keys(cmds).length+" команд — ОК");
